"""Summarise every real-hardware run in out/runs/ into out/HARDWARE_RESULTS.md and out/hardware_results.png."""

from __future__ import annotations

import glob
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "out"
rows = []
for f in sorted(glob.glob(str(OUT / "runs" / "*.analysis.json"))):
    name = Path(f).name
    if not (name.startswith("ibm-ibm") or name.startswith("iqm-garnet") or name.startswith("iqm-emerald")
            or name.startswith("q50") or name.startswith("q20")):
        continue          # skip simulator / fake-backend rehearsals
    run = json.loads(Path(f.replace(".analysis.json", ".json")).read_text())
    for inst, s in json.loads(Path(f).read_text()).items():
        rows.append({
            "file": name.replace(".analysis.json", ""), "device": run.get("device", run["backend"]),
            "platform": "IBM" if run["backend"] == "ibm" else ("IQM" if run["backend"] == "iqm" else run["backend"].upper()),
            "job": ", ".join(run.get("jobs", [])), "created": run["created_utc"], "instance": inst,
            "copies": s.get("copies", 1), "best_qubits": bool(run.get("layout_triples")), "ks": run["ks"],
            "shots": s["shots"], "exact": s["exact"], "raw": s["raw_mlae"], "aware": s["noise_aware_mlae"],
            "per_copy": s.get("noise_aware_per_copy_mlae"), "k0": s["k0_only"],
            "gates": s["two_qubit_gates_by_k"], "mc_same_queries": s["mc_rmse_same_queries"],
        })

pct = lambda x: "–" if x is None else f"{100 * x:.3f} %"  # noqa: E731
md = ["# Real quantum hardware results", "",
      "Generated by `scripts/hardware_summary.py` from `out/runs/`. Exact values come from the two-level flood model "
      "(the circuit's own model). 'Corrected' = noise-aware MLAE using two calibration circuits with known answers, "
      "run in the same job on the same qubits. Classical Monte Carlo with the same number of model evaluations is "
      "shown as the honest reference: on today's hardware it is more precise.", "",
      "| Run | Instance | Copies | Shots | Exact | Raw | Corrected | First pass (k=0) | 2q gates by k | MC ± (same budget) |",
      "|---|---|---|---|---|---|---|---|---|---|"]
for r in rows:
    corr = r["per_copy"] if r["per_copy"] else r["aware"]
    label = "Kittilä + Ivalo both" if r["instance"].startswith("A3") else "≥2 of 3 Lapland"
    md.append(f"| {r['platform']} {r['device']} ({r['created'][:13]}){' best qubits' if r['best_qubits'] else ''} | {label} | "
              f"{r['copies']} | {r['shots']:,} | {pct(r['exact'])} | {pct(r['raw'])} | **{pct(corr)}** | {pct(r['k0'])} | "
              f"{'/'.join(str(v) for v in r['gates'].values())} | ±{100 * r['mc_same_queries']:.3f} pp |")
md += ["", "Job ids:", *[f"- {r['platform']} {r['device']} {r['created']}: `{r['job']}`" for r in rows
                         if r["instance"].startswith("A3")], "",
       "## What it shows",
       "- Both IBM and IQM hardware run the joint-flood amplitude-estimation circuit; raw readings are 2–3× the exact "
       "value (readout errors and gate noise), and the two-circuit calibration removes most of that bias.",
       "- Shallow circuits survive (3 qubits, ≤ ~50 two-qubit gates); the deeper 4-qubit amplified circuits lose most of "
       "their signal, especially on IBM. That is the measured limit of today's hardware.",
       "- Classical Monte Carlo at the same budget is still more precise. No quantum advantage is claimed.",
       "- 'Best qubits' on IBM uses today's calibration data; IQM publishes none through this API, so there the copies are "
       "only placed on well-separated qubits. The first IQM run had 1 copy (small sample, ±0.05 pp shot noise).",
       "- The independence line (0.040 %) is what P(both) would be if the two areas flooded independently: every run, "
       "even raw, is far above it, i.e. the hardware reproduces the co-flooding."]
for f in sorted(glob.glob(str(OUT / "runs" / "loader-iqm-emerald-*.json")) + sorted(glob.glob(str(OUT / "runs" / "loader-ibm-*.json"))) + sorted(glob.glob(str(OUT / "runs" / "loader-q50-*.json")))):
    r = json.loads(Path(f).read_text())
    if "p_at_least_k_exact" not in r:
        continue
    lvl = r.get("level", 0.1)
    lvl_txt = "1-in-10" if abs(lvl - 0.1) < 1e-9 else ("1-in-50" if abs(lvl - 0.02) < 1e-9 else f"p={lvl}")
    md += ["", f"## Full-scale loader at the {lvl_txt} level: all 14 areas on {r['device']} ({r['qubits']} qubits, {r['two_qubit_gates']} two-qubit gates)",
           f"Job `{r['jobs'][0]}`, {r['shots']:,} shots, readout flip rates {100*r['readout_p01']:.1f} % / {100*r['readout_p10']:.1f} %. "
           + ("Chart: `out/loader_emerald.png`." if lvl_txt == "1-in-10" else
            "At this rare level, gate noise creates false triggers that swamp the true signal: the measured limit of today's hardware."), "",
           (f"| k areas over {lvl_txt} | Hardware (readout-corrected) | Exact model | Independence | Observed 1961–2025 |"),
           "|---|---|---|---|---|"]
    obsd = {}
    oj = r.get("observed_reference") or {}
    if "k" in oj and lvl_txt == "1-in-10":      # observed years exist only at the 1-in-10 level
        obsd = dict(zip(oj["k"], oj["observed"]))
    for k in range(2, 8):
        md.append(f"| ≥{k} | {100*r['p_at_least_k_readout_corrected'][k]:.1f} % | {100*r['p_at_least_k_exact'][k]:.1f} % | "
                  f"{100*r['p_at_least_k_independent'][k]:.2f} % | {('%.1f %%' % (100*obsd[k])) if k in obsd else '–'} |")
snow = sorted(glob.glob(str(OUT / "runs" / "product-iqm-emerald-*.analysis.json")))
if snow:
    d = json.loads(Path(snow[-1]).read_text())
    rows_s = [(lab, d.get(f"A3_kittila_ivalo_both_{key}")) for lab, key in (("Low-snow March", "low"),
              ("Normal (no outlook)", "clim"), ("Snowy March (top 15 %)", "high"))]
    if all(r for _, r in rows_s):
        lo, hi = rows_s[0][1], rows_s[2][1]
        md += ["", "## The March snow signal, measured on IQM Emerald",
               f"Kittilä + Ivalo both over 1-in-50, 3 qubits, {lo['copies']} side-by-side copies, {lo['shots']:,} shots "
               f"per instance (run by Vaishnav, `{Path(snow[-1]).name.replace('.analysis.json', '')}`).", "",
               "| March snow | Exact | Hardware raw | Hardware calibrated |", "|---|---|---|---|"]
        for lab, r in rows_s:
            md.append(f"| {lab} | {100*r['exact']:.3f} % | {100*r['raw_mlae']:.3f} % | **{100*r['noise_aware_mlae']:.3f} %** |")
        bci = OUT / "bootstrap_ci.json"  # scripts/bootstrap_ci.py: ratio with a bootstrap 90 % interval
        sr = json.loads(bci.read_text()).get("snow_ratio_high_over_low") if bci.exists() else None
        if sr:
            md += ["", f"Snowy vs low-snow risk ratio: on the chip **{sr['estimate']:.2f}×** (bootstrap 90 % CI "
                   f"{sr['ci90'][0]:.1f}–{sr['ci90'][1]:.1f}) vs exact **{sr['exact']:.2f}×**. The interval contains the exact "
                   "ratio: the early-warning signal survives on real hardware."]
        else:
            md += ["", f"Snowy vs low-snow risk ratio: exact **{hi['exact']/lo['exact']:.2f}×**, on the chip "
                   f"**{hi['noise_aware_mlae']/lo['noise_aware_mlae']:.2f}×**. The early-warning signal survives on real hardware."]
q = sorted(glob.glob(str(OUT / "runs" / "qrisp_qae_iqm_*.json")))
if q:
    qr = json.loads(Path(q[-1]).read_text())
    md += ["", "## Qrisp implementation on IQM Garnet",
           "Same 3-qubit joint-trigger circuit written natively in Qrisp (IQM's high-level framework), compiled with IQM's "
           "pass manager (4 / 23 / 45 CZ for k = 0 / 1 / 2), run on IQM Garnet without the calibration circuits: raw "
           "MLAE matches the raw Qiskit run on the same chip. File: `" + Path(q[-1]).name + "`."]
(OUT / "HARDWARE_RESULTS.md").write_text("\n".join(md) + "\n")

import matplotlib  # noqa: E402
matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402

a3 = [r for r in rows if r["instance"].startswith("A3")]
fig, ax = plt.subplots(figsize=(10, 5.2))
labels = [f"{r['platform']} {r['device']}\n{('best qubits, ' if r['platform'] == 'IBM' else 'separated qubits, ') if r['best_qubits'] else ''}{r['copies']} cop{'ies' if r['copies'] > 1 else 'y'}"
          for r in a3]
x = range(len(a3))
ax.bar([i - 0.2 for i in x], [100 * r["raw"] for r in a3], 0.38, color="#c9d1d9", label="Raw hardware")
ax.bar([i + 0.2 for i in x], [100 * (r["per_copy"] or r["aware"]) for r in a3], 0.38, color="#1f6feb",
       label="Hardware + calibration")
ax.axhline(100 * a3[0]["exact"], color="#2da44e", lw=2.5, label=f"Exact {100 * a3[0]['exact']:.3f} %")
ax.axhline(100 * 0.0004, color="#cf222e", lw=1.5, ls="--", label="If areas were independent 0.040 %")
ax.set_xticks(list(x), labels, fontsize=9)
ax.set_ylabel("P(Kittilä and Ivalo both pass 1-in-50), %")
ax.set_title("Joint-flood probability on real quantum computers (3-qubit amplitude estimation)", loc="left")
ax.legend(frameon=False, fontsize=9)
ax.grid(axis="y", alpha=0.25)
fig.tight_layout()
fig.savefig(OUT / "hardware_results.png", dpi=130)
print("\n".join(md[:14]))
